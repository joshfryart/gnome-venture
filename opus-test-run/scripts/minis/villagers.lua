if only then for k in only:gmatch("[^,]+") do want[k] = true end end
local function spec(n, name)
  local f = { species = n[2], face = n[3], hat = n[4], hatc = n[5], cloth = n[6] }
  for k, v in pairs(n[7]) do f[k] = v end
  return { slug = name, size = "party", arch = "folk", col = n[3], feat = f, base = "moss" }
end
