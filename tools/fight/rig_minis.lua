-- Builds the fight-engine rigs for every creature miniature, from the same archetype code that draws the minis (opus-test-run/scripts/minis/lib.lua).
--   GV_ROOT=$PWD/ RIG=1 aseprite -b --script tools/fight/rig_minis.lua      (ONLY=slug,slug to limit; the data file is then not written)
-- Writes game/assets/img/fight/rig-<slug>.png (atlas: one column per part, row 0 paint, row 1 ink) and game/assets/fightrigs.js
-- (FE_RIGS = { skel: { key: { part: [parent, a, b, under] } }, rigs: { slug: [key, frame w, frame h, scale u, "part,part,..."] } }).
-- Pivots are in figure space (a right, b up from the feet, in units of u): the engine turns them into frame px.
local ROOT = os.getenv("GV_ROOT") or error("set GV_ROOT to the repo root (trailing slash)")
assert(os.getenv("RIG"), "run with RIG=1 (so the mini scripts only hand over their lists)")
local L = dofile(ROOT .. "opus-test-run/scripts/minis/lib.lua")
local list = dofile(ROOT .. "opus-test-run/scripts/minis/enemies.lua")
for _, s in ipairs(dofile(ROOT .. "opus-test-run/scripts/minis/villagers.lua")) do list[#list + 1] = s end
local only = os.getenv("ONLY"); local want = {}
if only then for k in only:gmatch("[^,]+") do want[k] = true end end
local dir = ROOT .. "game/assets/img/fight/"
local function num(v) local t = string.format("%.2f", v):gsub("0+$", ""):gsub("%.$", ""); return t end
local skel, skeys, rigs = {}, {}, {}
for _, s in ipairs(list) do
  if not only or want[s.slug] then
    local r = L.rig(s, dir)
    if not skel[r.key] then
      local t = {}
      for _, j in ipairs(r.skel) do t[#t + 1] = string.format('%s:[%s,%s,%s,%d]', j[1], j[2] and ('"' .. j[2] .. '"') or "0", num(j[3]), num(j[4]), j[5]) end
      skel[r.key] = "{" .. table.concat(t, ",") .. "}"; skeys[#skeys + 1] = r.key
    end
    rigs[#rigs + 1] = string.format('"%s":["%s",%d,%d,%s,"%s"]', s.slug, r.key, r.fw, r.fh, num(r.u), table.concat(r.ids, ","))
    print(string.format("%-24s %-12s %dx%d u=%s parts=%d", s.slug, r.key, r.fw, r.fh, num(r.u), #r.ids))
  end
end
if not only then
  table.sort(skeys); table.sort(rigs)
  local out = { "/* GENERATED by tools/fight/rig_minis.lua: do not edit. Creature rigs for assets/fightengine.js (bones per archetype, one row per creature). */", "window.FE_RIGS={skel:{" }
  for i, k in ipairs(skeys) do out[#out + 1] = '"' .. k .. '":' .. skel[k] .. (i < #skeys and "," or "") end
  out[#out + 1] = "},rigs:{"
  for i, r in ipairs(rigs) do out[#out + 1] = r .. (i < #rigs and "," or "") end
  out[#out + 1] = "}};"
  local f = assert(io.open(ROOT .. "game/assets/fightrigs.js", "w")); f:write(table.concat(out, "\n") .. "\n"); f:close()
  print(#rigs .. " rigs, " .. #skeys .. " skeletons -> game/assets/fightrigs.js")
end
