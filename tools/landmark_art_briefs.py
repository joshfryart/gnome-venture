#!/usr/bin/env python3
"""Writes claude/landmark-art-briefs.md: one brief per unique location (landmarks.txt) for the wonder-scene art set.
Slug = name lowercased, non-alphanumerics to hyphens. File = game/assets/img/wonders/<type>-<slug>.png (480x270)."""
import re, os, sys, json
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = R + '/game/includes/data/'
def slug(n): return re.sub(r'-+', '-', re.sub(r'[^a-z0-9]+', '-', n.lower().replace("'", ''))).strip('-')
wt = {}
for l in open(D + 'wonder_text.txt', encoding='utf8'):
    if l.startswith('#') or l.startswith('*') or '|' not in l: continue
    p = l.rstrip('\n').split('|')
    if len(p) >= 4: wt[p[0]] = p[1:4]
tw = {}
for l in open(D + 'towns.txt', encoding='utf8'):
    p = l.rstrip('\n').split('|')
    if len(p) > 7 and p[0] == 'S': tw[p[4]] = p[7]
rows = []
for l in open(D + 'landmarks.txt', encoding='utf8'):
    if l.startswith('#') or l.count('|') < 4: continue
    reg, z, typ, name, fl = l.rstrip('\n').split('|')[:5]
    rows.append(dict(region=reg, zone=int(z), type=typ, name=name, flavour=fl, slug=(slug(name) if slug(name).startswith(typ + '-') else typ + '-' + slug(name)),
                     intro=(wt.get(name) or [''])[0], win=(wt.get(name) or ['', '', ''])[1], town=tw.get(name, '')))
order = {'haven': 0, 'wonder': 1, 'delve': 2, 'lair': 3}
rows.sort(key=lambda r: (order[r['type']], r['region'], r['zone']))
if '--json' in sys.argv: print(json.dumps(rows, ensure_ascii=False, indent=1)); sys.exit()
o = ['# Unique-location scene art: briefs', '', 'Generated by `python3 tools/landmark_art_briefs.py`. 480x270 PNG each, `game/assets/img/wonders/<slug>.png`.', '']
for r in rows:
    o.append('## `%s`  (%s, region %s, zone %d)' % (r['slug'], r['type'], r['region'], r['zone']))
    o.append('**%s**. %s' % (r['name'], r['flavour']))
    if r['intro']: o.append('- Scene text: %s' % r['intro'])
    if r['win']: o.append('- On success: %s' % r['win'])
    if r['town']: o.append('- Town text: %s' % r['town'])
    o.append('')
open(R + '/claude/landmark-art-briefs.md', 'w', encoding='utf8').write('\n'.join(o))
print(len(rows), 'briefs')
