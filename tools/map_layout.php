<?php
declare(strict_types=1);
/**
 * Dumps the fixed region map layouts (game/includes/region_layout.php) for the art scripts.
 *   php tools/map_layout.php [GAME_DIR] > out.json
 * Prints JSON for all 14 regions (480 x 270 frame, the size of the region map art) and also writes tools/map_layout.lua
 * (`return { ... }`) so an Aseprite script can read it with dofile(). Each region: town, stops (every road stop, exit and
 * off-road place, found or not), roads (polylines town → exit), trails (stop → off-road place), exits (on the frame edge,
 * the side of the neighbouring region), pin (one flat spot: the town square) and clear (keep-clear circles round every marker).
 * Uses GAME_DIR's own database when it is installed (config.php); otherwise seeds a throwaway SQLite world the way
 * install.php does (the layout depends only on the world, never on players).
 */
if (PHP_SAPI !== 'cli') exit;
$game = rtrim($argv[1] ?? dirname(__DIR__) . '/game', '/');
$tmp = null;
if (is_file($game . '/config.php')) {
    require $game . '/includes/bootstrap.php';
} else {
    define('APP_ROOT', $game);
    define('APP_VERSION', preg_match("/define\\('APP_VERSION', '([0-9.]+)'\\)/", (string)@file_get_contents($game . '/includes/bootstrap.php'), $m) ? $m[1] : '0');
    require $game . '/includes/db.php';
    require $game . '/includes/functions.php';
    require $game . '/includes/pixel_art.php';
    require $game . '/includes/seed.php';
    $tmp = tempnam(sys_get_temp_dir(), 'gvmap');
    $GLOBALS['CONFIG'] = ['db' => ['driver' => 'sqlite', 'path' => $tmp], 'base_url' => ''];
    ob_start();
    db_migrate(db(), 'sqlite');
    db()->beginTransaction();
    foreach (settings_schema() as $k => $def) set_setting($k, (string)$def['default']);
    setting('__reload__');
    seed_starter_content();
    db()->commit();
    ob_end_clean();
}
require_once $game . '/includes/maps.php';
require_once $game . '/includes/region_layout.php';

$out = [];
foreach (q('SELECT code FROM regions ORDER BY id')->fetchAll(PDO::FETCH_COLUMN) as $code) {
    $L = region_layout((string)$code);
    if (!$L) continue;
    $t = $L['slots'][$L['town']];
    $stops = [];
    foreach ($L['slots'] as $s) {
        if ($s['type'] === 'town') continue;
        $stops[] = ['id' => $s['id'], 'kind' => $s['kind'], 'type' => $s['type'], 'x' => $s['x'], 'y' => $s['y'], 'r' => $s['r'], 'road' => $s['road'],
            'anchor' => $s['anchor'] ?: null, 'name' => $s['type'] === 'far' ? $s['farname'] : (string)$s['loc']['name']];
    }
    $out[] = ['code' => $L['code'], 'w' => $L['w'], 'h' => $L['h'], 'town' => ['id' => $t['id'], 'x' => $t['x'], 'y' => $t['y'], 'r' => $t['r'], 'name' => (string)$t['loc']['name']],
        'stops' => $stops, 'roads' => array_map(fn($r) => ['name' => $r['name'], 'to' => $r['far'], 'pts' => $r['pts']], $L['roads']),
        'trails' => array_map(fn($r) => $r['pts'], $L['trails']),
        'exits' => array_map(fn($e) => ['road' => $e['road'], 'to' => $e['to'], 'name' => $e['name'], 'x' => $e['x'], 'y' => $e['y'], 'side' => $e['side']], $L['exits']),
        'pin' => $L['pin'], 'clear' => array_map(fn($c) => [$c['x'], $c['y'], $c['r']], $L['clear'])];
}
if ($tmp) { $GLOBALS['CONFIG'] = null; @unlink($tmp); @unlink($tmp . '-wal'); @unlink($tmp . '-shm'); }

echo json_encode(['frame' => [RL_W, RL_H], 'regions' => $out], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), "\n";

/** A PHP value as a Lua literal (lists become 1-based arrays; road indexes stay 0-based numbers as in the JSON). */
function lua_val($v, string $ind = ''): string
{
    if ($v === null) return 'nil';
    if (is_bool($v)) return $v ? 'true' : 'false';
    if (is_int($v) || is_float($v)) return (string)$v;
    if (is_string($v)) return '"' . addcslashes($v, "\\\"\n\r") . '"';
    $list = array_is_list($v);
    $flat = $list && !array_filter($v, 'is_array');
    $parts = [];
    foreach ($v as $k => $x) $parts[] = ($list ? '' : (preg_match('/^[A-Za-z_]\w*$/', (string)$k) ? $k : '["' . $k . '"]') . ' = ') . lua_val($x, $ind . '  ');
    if ($flat || count($parts) === 0) return '{ ' . implode(', ', $parts) . ' }';
    return "{\n" . $ind . '  ' . implode(",\n" . $ind . '  ', $parts) . "\n" . $ind . '}';
}
$lua = "-- Generated by tools/map_layout.php: the fixed region map layouts (480 x 270 frame; the art grid is half that, so divide by 2).\n"
    . "-- Roads/exits use 0-based road numbers. Regenerate after any change to roads or places: php tools/map_layout.php > /dev/null\n"
    . 'return ' . lua_val(['frame' => [RL_W, RL_H], 'regions' => array_combine(array_column($out, 'code'), $out)]) . "\n";
file_put_contents(__DIR__ . '/map_layout.lua', $lua);
