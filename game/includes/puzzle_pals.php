/** Tables + the users columns, in the [tables, indexes, columns] shape schema.php merges (fresh installs); ppal_ensure() does the same for old databases. */
function ppal_schema(string $PK, string $ID, string $END): array
{
    $t = ["CREATE TABLE IF NOT EXISTS ppal_releases (
        id $PK,
        user_id $ID NOT NULL,
        pic_id $ID NOT NULL,
        released_at DATETIME NOT NULL,
        src VARCHAR(8) NOT NULL DEFAULT 'free',
        run_id $ID NULL,
        UNIQUE (user_id, pic_id)
    )$END", "CREATE TABLE IF NOT EXISTS ppal_found (
        id $PK,
        user_id $ID NOT NULL,
        pal_key VARCHAR(48) NOT NULL,
        pic_id $ID NOT NULL,
        found_at DATETIME NOT NULL,
        times INT NOT NULL DEFAULT 1,
        active INT NOT NULL DEFAULT 0,
        UNIQUE (user_id, pal_key)
    )$END", "CREATE TABLE IF NOT EXISTS ppal_trophies (
        id $PK,
        user_id $ID NOT NULL,
        pic_id $ID NOT NULL,
        earned_at DATETIME NOT NULL,
        src VARCHAR(8) NOT NULL DEFAULT 'free',
        run_id $ID NULL,
        UNIQUE (user_id, pic_id)
    )$END", "CREATE TABLE IF NOT EXISTS ppal_spawns (
        id $PK,
        user_id $ID NOT NULL,
        pal_key VARCHAR(48) NOT NULL,
        pic_id $ID NOT NULL,
        loc_id $ID NOT NULL,
        made_day VARCHAR(10) NOT NULL,
        UNIQUE (user_id, pal_key)
    )$END"];
    $i = ['CREATE INDEX idx_ppal_found_pic ON ppal_found (user_id, pic_id)'];
    $c = [['users', 'ppal_at', 'DATETIME NULL'], ['users', 'ppal_day', 'VARCHAR(10) NULL'], ['users', 'ppal_count', 'INT NOT NULL DEFAULT 0'], ['users', 'ppal_spawn_day', 'VARCHAR(10) NULL']];
    return [$t, $i, $c];
}

/** Make the tables and users columns if the upgrade has not run yet (guarded like jigsaw_ensure). False = no tables, callers do nothing. */
function ppal_ensure(): bool
{
    static $ok = null;
    if ($ok !== null) return $ok;
    try { q('SELECT 1 FROM ppal_releases LIMIT 1'); q('SELECT 1 FROM ppal_found LIMIT 1'); q('SELECT 1 FROM ppal_trophies LIMIT 1'); q('SELECT 1 FROM ppal_spawns LIMIT 1'); $ok = true; } catch (Throwable $e) { $ok = false; }
    try {
        $s = db()->getAttribute(PDO::ATTR_DRIVER_NAME) === 'sqlite';
        [$t, $i, $c] = ppal_schema($s ? 'INTEGER PRIMARY KEY AUTOINCREMENT' : 'INT UNSIGNED AUTO_INCREMENT PRIMARY KEY', $s ? 'INTEGER' : 'INT UNSIGNED', $s ? '' : ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci');
        if (!$ok) {
            foreach ($t as $sql) db()->exec($sql);
            foreach ($i as $sql) { try { db()->exec($sql); } catch (Throwable $e) {} }
            $ok = true;
        }
        foreach ($c as [$tb, $col, $def]) {
            try { q("SELECT $col FROM $tb LIMIT 1"); } catch (Throwable $e) { db()->exec("ALTER TABLE $tb ADD COLUMN $col $def"); }
        }
    } catch (Throwable $e) {
        error_log('ppal_ensure: ' . $e->getMessage());
        return $ok = false;
    }
    return $ok;
}

// ---------------- data: authored rows + generated rosters ----------------

/** includes/data/puzzle_pals.txt parsed once: pic slug => list of pal rows (assoc). Bad lines are skipped (tools/lint_puzzle_pals.py reports them). */
function ppal_data(): array
{
    static $d = null;
    if ($d !== null) return $d;
    $d = [];
    $f = __DIR__ . '/data/puzzle_pals.txt';
    foreach (is_file($f) ? (file($f, FILE_IGNORE_NEW_LINES) ?: []) : [] as $l) {
        if (trim($l) === '' || $l[0] === '#') continue;
        $c = explode('|', $l);
        if (count($c) !== PPAL_COLS) continue;
        $d[$c[0]][] = ppal_row($c[0], array_slice($c, 1));
    }
    return $d;
}

/** One pal row from its columns after pic_slug: key, name, rarity, calling, grit, nimble, hardiness, luck, piece, shape, knob, perk, blurb. */
function ppal_row(string $pic, array $c): array
{
    $calling = (string)$c[3];
    $perk = (string)$c[11];
    return ['pic' => $pic, 'key' => (string)$c[0], 'name' => (string)$c[1], 'rarity' => (string)$c[2], 'calling' => $calling,
        'grit' => (int)$c[4], 'nimble' => (int)$c[5], 'hardiness' => (int)$c[6], 'luck' => (int)$c[7], 'piece' => (string)$c[8],
        'shape' => (string)$c[9], 'knob' => (string)$c[10], 'perk' => in_array($perk, PPAL_PERKS, true) ? $perk : (PPAL_CALLING_PERK[$calling] ?? 'shine'), 'blurb' => (string)$c[12]];
}

/** The name banks (includes/data/puzzle_pal_names.txt): ['first' => kind => [names], 'epithet' => kind => [words]]. */
function ppal_names(): array
{
    static $n = null;
    if ($n !== null) return $n;
    $n = ['first' => [], 'epithet' => []];
    $f = __DIR__ . '/data/puzzle_pal_names.txt';
    foreach (is_file($f) ? (file($f, FILE_IGNORE_NEW_LINES) ?: []) : [] as $l) {
        $c = explode('|', $l);
        if (count($c) === 3 && isset($n[$c[0]])) $n[$c[0]][$c[1]] = array_values(array_filter(explode(',', $c[2]), 'strlen'));
    }
    return $n;
}

/** The slug a picture is known by in the data file: built-ins lose their "jig-", Places and uploads keep the table slug. */
function ppal_pic_slug(array $pic): string
{
    $s = (string)($pic['slug'] ?? '');
    return ($pic['source'] ?? '') === 'builtin' && str_starts_with($s, 'jig-') ? substr($s, 4) : $s;
}

/** Place kind of a picture (haven / wonder / delve / lair) from its unlock key; uploads count as 'wonder'. */
function ppal_pic_kind(array $pic): string
{
    $k = strstr((string)($pic['unlock_key'] ?? ''), '-', true);
    return in_array($k, PPAL_PLACE_KINDS, true) ? $k : 'wonder';
}

/** A stable unsigned hash of a string (the crc32(slug) seed of the plan: every draw is crc32(slug:what:n), so a place always gets the same 6). */
function ppal_h(string $s): int
{
    return crc32($s) & 0xFFFFFFFF;
}

/**
 * The generated roster of a Places or upload picture: names from the banks by crc32(slug) draws, the 3/2/1 recipe of shapes (corner + edge + inner / two of
 * Plus, Ring, TTBB / one whimsy), the place kind's callings and knobs, stats in the rarity band. An authored row for the slug (ppal_roster) overrides it.
 */
function ppal_place_roster(array $pic): array
{
    $slug = ppal_pic_slug($pic);
    $kind = ppal_pic_kind($pic);
    $names = ppal_names();
    $firsts = $names['first'][$kind] ?? [];
    $eps = $names['epithet'][$kind] ?? [];
    if (!$firsts || !$eps || $slug === '') return [];
    [$callings, $knobs, $whims] = PPAL_KIND_STYLE[$kind];
    $ladder = ['common', 'uncommon', 'rare', 'common', 'uncommon', 'common'];   // first n of these: 6 = 3 common, 2 uncommon, 1 rare
    $commonShapes = [['corner-TT', 'corner-TB', 'corner-BB'], ['edge-TTB', 'edge-TBB', 'edge-TBT', 'edge-BTB'], ['inner-TBTB', 'inner-TTTB', 'inner-TBBB']];
    $uncShapes = ['inner-TTTT', 'inner-BBBB', 'inner-TTBB'];
    $title = (string)($pic['title'] ?? 'this picture');
    $out = [];
    $used = [];
    $cnt = ['common' => 0, 'uncommon' => 0, 'rare' => 0];
    $tag = substr(md5($slug), 0, 8);
    foreach (array_slice($ladder, 0, ppal_roster_size()) as $i => $rar) {
        $name = '';
        for ($t = 0; $t < 40; $t++) {
            $name = $firsts[ppal_h("$slug:f:$i:$t") % count($firsts)] . ' ' . $eps[ppal_h("$slug:e:$i:$t") % count($eps)];
            if (!isset($used[$name])) break;
        }
        $used[$name] = 1;
        $n = $cnt[$rar]++;
        if ($rar === 'common') {
            $fam = $commonShapes[$n % 3];
            $shape = $fam[ppal_h("$slug:s:$i") % count($fam)];
        } elseif ($rar === 'uncommon') {
            $shape = $uncShapes[(ppal_h("$slug:u") + $n) % 3];
        } else {
            $shape = $whims[ppal_h("$slug:w") % count($whims)];
        }
        $total = $rar === 'common' ? 3 + ppal_h("$slug:t:$i") % 2 : ($rar === 'uncommon' ? 5 : 6);
        $st = [0, 0, 0, 0];
        for ($k = 0, $p = ppal_h("$slug:p:$i"); $total > 0; $k++) {
            $j = ($p + $k) % 4;
            if ($st[$j] < 3) { $st[$j]++; $total--; }
        }
        $calling = $callings[ppal_h("$slug:c:$i") % count($callings)];
        $out[] = ['pic' => $slug, 'key' => 'g' . $tag . '-' . ($i + 1), 'name' => $name, 'rarity' => $rar, 'calling' => $calling,
            'grit' => $st[0], 'nimble' => $st[1], 'hardiness' => $st[2], 'luck' => $st[3],
            'piece' => (ppal_h("$slug:pc:$i") % 12) . '-' . (ppal_h("$slug:pr:$i") % 8), 'shape' => $shape, 'knob' => $knobs[($i + ppal_h("$slug:k")) % count($knobs)],
            'perk' => PPAL_CALLING_PERK[$calling], 'blurb' => 'A ' . $rar . ' Puzzle Pal that fell out of ' . $title . '.', 'generated' => true];
    }
    return $out;
}

/** The roster of a picture row: authored rows (cut to ppal_roster_size) or, for Places and uploads, the generated one. Built-in pictures with no authored row have none yet. */
function ppal_roster(array $pic): array
{
    if (($pic['kind'] ?? 'still') !== 'still') return [];
    $auth = ppal_data()[ppal_pic_slug($pic)] ?? null;
    if ($auth) return array_slice($auth, 0, ppal_roster_size());
    return in_array((string)($pic['source'] ?? ''), ['place', 'upload'], true) ? ppal_place_roster($pic) : [];
}

// ---------------- art ----------------

/** assets/img/puzzles/pals/<key>.png (64 px sticker). */
function ppal_art_file(string $key): string
{
    return APP_ROOT . '/assets/img/puzzles/pals/' . preg_replace('/[^a-z0-9_-]/i', '', $key) . '.png';
}

/** Is this file the red-bordered placeholder (tools/pal_briefs.py --placeholders copies one reference image, pals/_placeholder.png, under every name)? */
function ppal_is_placeholder(string $file): bool
{
    static $ref = null;
    if ($ref === null) $ref = is_file(APP_ROOT . '/assets/img/puzzles/pals/_placeholder.png') ? md5_file(APP_ROOT . '/assets/img/puzzles/pals/_placeholder.png') : '';
    return $ref !== '' && md5_file($file) === $ref;
}

/** The pal's sticker URL, or '' when its art is missing (callers then draw nothing or an emoji, never a broken image). */
function ppal_art_url(string $key): string
{
    $f = ppal_art_file($key);
    return is_file($f) ? url('assets/img/puzzles/pals/' . basename($f)) : '';
}

/** Art-ready gate: every pal of the roster has a real (non-placeholder) PNG. A picture that is not art-ready releases nothing (admins see and release all). */
function ppal_art_ready(array $pic): bool
{
    $r = ppal_roster($pic);
    if (!$r) return false;
    foreach ($r as $p) {
        $f = ppal_art_file($p['key']);
        if (!is_file($f) || ppal_is_placeholder($f)) return false;
    }
    return true;
}

// ---------------- release + trophy ----------------

function ppal_released(int $uid, int $picId): bool
{
    return ppal_ensure() && (bool)q_val('SELECT 1 FROM ppal_releases WHERE user_id = ? AND pic_id = ?', [$uid, $picId]);
}

function ppal_has_trophy(int $uid, int $picId): bool
{
    return ppal_ensure() && (bool)q_val('SELECT 1 FROM ppal_trophies WHERE user_id = ? AND pic_id = ?', [$uid, $picId]);
}

/** Pictures this gnome holds an Expert trophy for: pic_id => earned_at. */
function ppal_trophies(int $uid): array
{
    if (!ppal_ensure()) return [];
    try { return q('SELECT pic_id, earned_at FROM ppal_trophies WHERE user_id = ?', [$uid])->fetchAll(PDO::FETCH_KEY_PAIR); } catch (Throwable $e) { return []; }
}

/** Perk units the Expert trophy adds to this picture's pals (+4 percent, +1 point for road; only while ppal_party is on and the gnome holds the trophy). */
function ppal_trophy_unit(int $uid, int $picId, string $perk = ''): int
{
    return setting('ppal_party') === '1' && ppal_has_trophy($uid, $picId) ? ($perk === 'road' ? 1 : PPAL_TROPHY_UNITS) : 0;
}

/** A pal's perk units: its rarity's worth (percent, or road points) plus the Expert trophy of its picture. */
function ppal_pal_units(array $pal, int $uid, int $picId): int
{
    $k = (string)$pal['perk'];
    return ($k === 'road' ? (PPAL_ROAD_UNITS[$pal['rarity']] ?? 1) : (PPAL_UNITS[$pal['rarity']] ?? 8)) + ppal_trophy_unit($uid, $picId, $k);
}

/**
 * A timed jigsaw was just DONE (server-verified by the caller: min time, drops, single-use token). Advanced (96) releases the picture's roster; Expert (216)
 * earns its trophy; Easy does nothing. Once per (gnome, picture) each. Skips guests, a closed feature, and (for players) a roster whose art is not ready.
 * $src 'free' | 'tourney'. Returns what is NEW for the win card: ['title', 'released' => pals, 'trophy' => bool], or [] (also on any error: never breaks a finish).
 */
function ppal_on_solve(int $uid, int $picId, string $tier, string $src, int $runId = 0): array
{
    try {
        if ($tier !== 'advanced' && $tier !== 'expert') return [];
        if (is_guest_uid($uid) || !ppal_open() || !ppal_ensure()) return [];
        $pic = q_one("SELECT * FROM puzzle_pics WHERE id = ? AND kind = 'still'", [$picId]);
        if (!$pic) return [];
        $src = $src === 'tourney' ? 'tourney' : 'free';
        $out = [];
        if ($tier === 'advanced') {
            if (!ppal_roster($pic) || (!is_admin() && !ppal_art_ready($pic))) return [];
            try {
                db_insert('ppal_releases', ['user_id' => $uid, 'pic_id' => $picId, 'released_at' => now(), 'src' => $src, 'run_id' => $runId ?: null]);
            } catch (Throwable $e) { return []; }   // UNIQUE: released already
            $out = ['title' => (string)$pic['title'], 'released' => count(ppal_roster($pic)), 'trophy' => false];
            try { q('UPDATE users SET ppal_spawn_day = NULL WHERE id = ?', [$uid]); } catch (Throwable $e) {}   // v2.0.92: the new roster gets its map spawns on the next page
            require_once __DIR__ . '/trade.php';
            notify($uid, '🧩 The magic of the jigsaw is loose! ' . $out['released'] . ' Puzzle Pals from ' . $pic['title'] . ' are somewhere about the Hollow.');
        } else {
            try {
                db_insert('ppal_trophies', ['user_id' => $uid, 'pic_id' => $picId, 'earned_at' => now(), 'src' => $src, 'run_id' => $runId ?: null]);
            } catch (Throwable $e) { return []; }   // UNIQUE: trophy already
            $out = ['title' => (string)$pic['title'], 'released' => 0, 'trophy' => true];
        }
        return $out;
    } catch (Throwable $e) {
        error_log('ppal_on_solve: ' . $e->getMessage());
        return [];
    }
}

// ---------------- step 2: the find lane (events.php calls ppal_maybe_find after the ordinary event roll found nothing) ----------------

/** A picture row by id (still pictures only). */
function ppal_pic(int $picId): ?array
{
    static $c = [];
    if (!array_key_exists($picId, $c)) $c[$picId] = q_one("SELECT * FROM puzzle_pics WHERE id = ? AND kind = 'still'", [$picId]) ?: null;
    return $c[$picId];
}

/** Pictures this gnome has released: pic_id => released_at. */
function ppal_releases(int $uid): array
{
    if (!ppal_ensure()) return [];
    try { return q('SELECT pic_id, released_at FROM ppal_releases WHERE user_id = ? ORDER BY released_at, id', [$uid])->fetchAll(PDO::FETCH_KEY_PAIR); } catch (Throwable $e) { return []; }
}

/** What this gnome has found: pal_key => ['times', 'found_at', 'active', 'pic_id']. */
function ppal_found_map(int $uid): array
{
    if (!ppal_ensure()) return [];
    $o = [];
    try { foreach (q('SELECT pal_key, pic_id, found_at, times, active FROM ppal_found WHERE user_id = ?', [$uid])->fetchAll() as $r) $o[$r['pal_key']] = $r; } catch (Throwable $e) {}
    return $o;
}

/** A pal row by key inside a picture's roster, or null. */
function ppal_find_pal(array $pic, string $key): ?array
{
    foreach (ppal_roster($pic) as $p) if ($p['key'] === $key) return $p;
    return null;
}

/**
 * Pick the pal a find shows: missing pals of released pictures first (weighted by rarity), duplicates only when every released roster is complete.
 * $test (the admin's button) with nothing released picks from the first picture that has a roster. Returns ['pal' => row, 'pic' => row, 'test' => bool] or null.
 */
function ppal_pick(int $uid, bool $test = false): ?array
{
    $rel = ppal_releases($uid);
    $have = ppal_found_map($uid);
    $missing = $all = [];
    foreach (array_keys($rel) as $picId) {
        $pic = ppal_pic((int)$picId);
        if (!$pic) continue;
        foreach (ppal_roster($pic) as $p) {
            $all[] = [$p, $pic];
            if (!isset($have[$p['key']])) $missing[] = [$p, $pic];
        }
    }
    $isTest = false;
    if (!$all && $test && is_admin()) {
        foreach (q("SELECT * FROM puzzle_pics WHERE kind = 'still' AND active = 1 ORDER BY sort, id")->fetchAll() as $pic) {
            if (($r = ppal_roster($pic))) { foreach ($r as $p) $all[] = [$p, $pic]; $missing = $all; $isTest = true; break; }
        }
    }
    $pool = $missing ?: $all;
    if (!$pool) return null;
    $tot = 0;
    foreach ($pool as [$p]) $tot += PPAL_RARITIES[$p['rarity']] ?? 10;
    $roll = random_int(1, max(1, $tot));
    foreach ($pool as [$p, $pic]) {
        $roll -= PPAL_RARITIES[$p['rarity']] ?? 10;
        if ($roll <= 0) return ['pal' => $p, 'pic' => $pic, 'test' => $isTest];
    }
    return ['pal' => $pool[0][0], 'pic' => $pool[0][1], 'test' => $isTest];
}

/**
 * The second lane of maybe_random_event(): a Puzzle Pal turns up. Own odds, cooldown and daily cap (users.ppal_*), never alongside another box
 * (the caller runs it only when the ordinary roll produced nothing), never on a quiet page, guests skipped. Sets $_SESSION['event_pending'] (slug 'ppal' + token).
 * The admin's "test a pal find" ($_SESSION['ppal_force']) skips the roll, cooldown and cap, never the quiet pages.
 */
function ppal_maybe_find(array $u): bool
{
    try {
        if (!ppal_open() || is_guest($u) || !ppal_ensure()) return false;
        if (ppal_find_mode() === 'map' && empty($_SESSION['ppal_force'])) return false;   // v2.0.92: pals wait on the map; the page lane is the old mode (setting ppal_find_mode = page)
        if (!empty($_SESSION['event_pending']) || !empty($_SESSION['event_box'])) return false;
        if (in_array(basename((string)($_SERVER['SCRIPT_NAME'] ?? '')), defined('PPAL_QUIET_PAGES') ? PPAL_QUIET_PAGES : [], true)) return false;   // PPAL_QUIET_PAGES is set in layout.php
        $uid = (int)$u['id'];
        $force = !empty($_SESSION['ppal_force']);
        $day = hollow_date('Y-m-d');
        if (!$force) {
            $chance = max(2, (int)setting('ppal_chance'));
            if (($fp = ppal_perks($u)['finder']) > 0) $chance = max(2, (int)round($chance / (1 + $fp / 100)));   // step 4: the finder perk (+5% per unit, cap +30%)
            if (random_int(1, $chance) !== 1) return false;
            $cool = max(0, (int)setting('ppal_cooldown_minutes')) * 60;
            if (!empty($u['ppal_at']) && strtotime($u['ppal_at'] . ' UTC') > time() - $cool) return false;
            if (($u['ppal_day'] ?? '') === $day && (int)($u['ppal_count'] ?? 0) >= (int)setting('ppal_daily_max')) return false;
        }
        $pick = ppal_pick($uid, $force);
        unset($_SESSION['ppal_force']);
        if (!$pick) return false;
        q('UPDATE users SET ppal_at = ?, ppal_count = CASE WHEN ppal_day = ? THEN ppal_count + 1 ELSE 1 END, ppal_day = ? WHERE id = ?', [now(), $day, $day, $uid]);
        $_SESSION['event_pending'] = ['slug' => 'ppal', 'token' => bin2hex(random_bytes(8)), 'pal' => $pick['pal']['key'], 'pic' => (int)$pick['pic']['id'], 'test' => $pick['test'] ? 1 : 0];
        return true;
    } catch (Throwable $e) {
        error_log('ppal_maybe_find: ' . $e->getMessage());
        return false;
    }
}

