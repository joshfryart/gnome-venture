/** Tables + the users columns, in the [tables, indexes, columns] shape schema.php merges (fresh installs); ppal_ensure() does the same for old databases. */
function ppal_schema(string $PK, string $ID, string $END): array
{
    $t = ["CREATE TABLE IF NOT EXISTS ppal_releases (
        id $PK,
        user_id $ID NOT NULL,
        pic_id $ID NOT NULL,
        released_at DATETIME NOT NULL,
        src VARCHAR(8) NOT NULL DEFAULT 'free',
        run_id $ID NULL,
        UNIQUE (user_id, pic_id)
    )$END", "CREATE TABLE IF NOT EXISTS ppal_found (
        id $PK,
        user_id $ID NOT NULL,
        pal_key VARCHAR(48) NOT NULL,
        pic_id $ID NOT NULL,
        found_at DATETIME NOT NULL,
        times INT NOT NULL DEFAULT 1,
        active INT NOT NULL DEFAULT 0,
        UNIQUE (user_id, pal_key)
    )$END", "CREATE TABLE IF NOT EXISTS ppal_trophies (
        id $PK,
        user_id $ID NOT NULL,
        pic_id $ID NOT NULL,
        earned_at DATETIME NOT NULL,
        src VARCHAR(8) NOT NULL DEFAULT 'free',
        run_id $ID NULL,
        UNIQUE (user_id, pic_id)
    )$END"];
    $i = ['CREATE INDEX idx_ppal_found_pic ON ppal_found (user_id, pic_id)'];
    $c = [['users', 'ppal_at', 'DATETIME NULL'], ['users', 'ppal_day', 'VARCHAR(10) NULL'], ['users', 'ppal_count', 'INT NOT NULL DEFAULT 0']];
    return [$t, $i, $c];
}

/** Make the tables and users columns if the upgrade has not run yet (guarded like jigsaw_ensure). False = no tables, callers do nothing. */
function ppal_ensure(): bool
{
    static $ok = null;
    if ($ok !== null) return $ok;
    try { q('SELECT 1 FROM ppal_releases LIMIT 1'); q('SELECT 1 FROM ppal_found LIMIT 1'); q('SELECT 1 FROM ppal_trophies LIMIT 1'); $ok = true; } catch (Throwable $e) { $ok = false; }
    try {
        $s = db()->getAttribute(PDO::ATTR_DRIVER_NAME) === 'sqlite';
        [$t, $i, $c] = ppal_schema($s ? 'INTEGER PRIMARY KEY AUTOINCREMENT' : 'INT UNSIGNED AUTO_INCREMENT PRIMARY KEY', $s ? 'INTEGER' : 'INT UNSIGNED', $s ? '' : ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci');
        if (!$ok) {
            foreach ($t as $sql) db()->exec($sql);
            foreach ($i as $sql) { try { db()->exec($sql); } catch (Throwable $e) {} }
            $ok = true;
        }
        foreach ($c as [$tb, $col, $def]) {
            try { q("SELECT $col FROM $tb LIMIT 1"); } catch (Throwable $e) { db()->exec("ALTER TABLE $tb ADD COLUMN $col $def"); }
        }
    } catch (Throwable $e) {
        error_log('ppal_ensure: ' . $e->getMessage());
        return $ok = false;
    }
    return $ok;
}

// ---------------- data: authored rows + generated rosters ----------------

/** includes/data/puzzle_pals.txt parsed once: pic slug => list of pal rows (assoc). Bad lines are skipped (tools/lint_puzzle_pals.py reports them). */
function ppal_data(): array
{
    static $d = null;
    if ($d !== null) return $d;
    $d = [];
    $f = __DIR__ . '/data/puzzle_pals.txt';
    foreach (is_file($f) ? (file($f, FILE_IGNORE_NEW_LINES) ?: []) : [] as $l) {
        if (trim($l) === '' || $l[0] === '#') continue;
        $c = explode('|', $l);
        if (count($c) !== PPAL_COLS) continue;
        $d[$c[0]][] = ppal_row($c[0], array_slice($c, 1));
    }
    return $d;
}

/** One pal row from its columns after pic_slug: key, name, rarity, calling, grit, nimble, hardiness, luck, piece, shape, knob, perk, blurb. */
function ppal_row(string $pic, array $c): array
{
    $calling = (string)$c[3];
    $perk = (string)$c[11];
    return ['pic' => $pic, 'key' => (string)$c[0], 'name' => (string)$c[1], 'rarity' => (string)$c[2], 'calling' => $calling,
        'grit' => (int)$c[4], 'nimble' => (int)$c[5], 'hardiness' => (int)$c[6], 'luck' => (int)$c[7], 'piece' => (string)$c[8],
        'shape' => (string)$c[9], 'knob' => (string)$c[10], 'perk' => in_array($perk, PPAL_PERKS, true) ? $perk : (PPAL_CALLING_PERK[$calling] ?? 'shine'), 'blurb' => (string)$c[12]];
}

/** The name banks (includes/data/puzzle_pal_names.txt): ['first' => kind => [names], 'epithet' => kind => [words]]. */
function ppal_names(): array
{
    static $n = null;
    if ($n !== null) return $n;
    $n = ['first' => [], 'epithet' => []];
    $f = __DIR__ . '/data/puzzle_pal_names.txt';
    foreach (is_file($f) ? (file($f, FILE_IGNORE_NEW_LINES) ?: []) : [] as $l) {
        $c = explode('|', $l);
        if (count($c) === 3 && isset($n[$c[0]])) $n[$c[0]][$c[1]] = array_values(array_filter(explode(',', $c[2]), 'strlen'));
    }
    return $n;
}

/** The slug a picture is known by in the data file: built-ins lose their "jig-", Places and uploads keep the table slug. */
function ppal_pic_slug(array $pic): string
{
    $s = (string)($pic['slug'] ?? '');
    return ($pic['source'] ?? '') === 'builtin' && str_starts_with($s, 'jig-') ? substr($s, 4) : $s;
}

/** Place kind of a picture (haven / wonder / delve / lair) from its unlock key; uploads count as 'wonder'. */
function ppal_pic_kind(array $pic): string
{
    $k = strstr((string)($pic['unlock_key'] ?? ''), '-', true);
    return in_array($k, PPAL_PLACE_KINDS, true) ? $k : 'wonder';
}

/** A stable unsigned hash of a string (the crc32(slug) seed of the plan: every draw is crc32(slug:what:n), so a place always gets the same 6). */
function ppal_h(string $s): int
{
    return crc32($s) & 0xFFFFFFFF;
}

/**
 * The generated roster of a Places or upload picture: names from the banks by crc32(slug) draws, the 3/2/1 recipe of shapes (corner + edge + inner / two of
 * Plus, Ring, TTBB / one whimsy), the place kind's callings and knobs, stats in the rarity band. An authored row for the slug (ppal_roster) overrides it.
 */
function ppal_place_roster(array $pic): array
{
    $slug = ppal_pic_slug($pic);
    $kind = ppal_pic_kind($pic);
    $names = ppal_names();
    $firsts = $names['first'][$kind] ?? [];
    $eps = $names['epithet'][$kind] ?? [];
    if (!$firsts || !$eps || $slug === '') return [];
    [$callings, $knobs, $whims] = PPAL_KIND_STYLE[$kind];
    $ladder = ['common', 'uncommon', 'rare', 'common', 'uncommon', 'common'];   // first n of these: 6 = 3 common, 2 uncommon, 1 rare
    $commonShapes = [['corner-TT', 'corner-TB', 'corner-BB'], ['edge-TTB', 'edge-TBB', 'edge-TBT', 'edge-BTB'], ['inner-TBTB', 'inner-TTTB', 'inner-TBBB']];
    $uncShapes = ['inner-TTTT', 'inner-BBBB', 'inner-TTBB'];
    $title = (string)($pic['title'] ?? 'this picture');
    $out = [];
    $used = [];
    $cnt = ['common' => 0, 'uncommon' => 0, 'rare' => 0];
    $tag = substr(md5($slug), 0, 8);
    foreach (array_slice($ladder, 0, ppal_roster_size()) as $i => $rar) {
        $name = '';
        for ($t = 0; $t < 40; $t++) {
            $name = $firsts[ppal_h("$slug:f:$i:$t") % count($firsts)] . ' ' . $eps[ppal_h("$slug:e:$i:$t") % count($eps)];
            if (!isset($used[$name])) break;
        }
        $used[$name] = 1;
        $n = $cnt[$rar]++;
        if ($rar === 'common') {
            $fam = $commonShapes[$n % 3];
            $shape = $fam[ppal_h("$slug:s:$i") % count($fam)];
        } elseif ($rar === 'uncommon') {
            $shape = $uncShapes[(ppal_h("$slug:u") + $n) % 3];
        } else {
            $shape = $whims[ppal_h("$slug:w") % count($whims)];
        }
        $total = $rar === 'common' ? 3 + ppal_h("$slug:t:$i") % 2 : ($rar === 'uncommon' ? 5 : 6);
        $st = [0, 0, 0, 0];
        for ($k = 0, $p = ppal_h("$slug:p:$i"); $total > 0; $k++) {
            $j = ($p + $k) % 4;
            if ($st[$j] < 3) { $st[$j]++; $total--; }
        }
        $calling = $callings[ppal_h("$slug:c:$i") % count($callings)];
        $out[] = ['pic' => $slug, 'key' => 'g' . $tag . '-' . ($i + 1), 'name' => $name, 'rarity' => $rar, 'calling' => $calling,
            'grit' => $st[0], 'nimble' => $st[1], 'hardiness' => $st[2], 'luck' => $st[3],
            'piece' => (ppal_h("$slug:pc:$i") % 12) . '-' . (ppal_h("$slug:pr:$i") % 8), 'shape' => $shape, 'knob' => $knobs[($i + ppal_h("$slug:k")) % count($knobs)],
            'perk' => PPAL_CALLING_PERK[$calling], 'blurb' => 'A ' . $rar . ' Puzzle Pal that fell out of ' . $title . '.', 'generated' => true];
    }
    return $out;
}

/** The roster of a picture row: authored rows (cut to ppal_roster_size) or, for Places and uploads, the generated one. Built-in pictures with no authored row have none yet. */
function ppal_roster(array $pic): array
{
    if (($pic['kind'] ?? 'still') !== 'still') return [];
    $auth = ppal_data()[ppal_pic_slug($pic)] ?? null;
    if ($auth) return array_slice($auth, 0, ppal_roster_size());
    return in_array((string)($pic['source'] ?? ''), ['place', 'upload'], true) ? ppal_place_roster($pic) : [];
}

// ---------------- art ----------------

/** assets/img/puzzles/pals/<key>.png (64 px sticker). */
function ppal_art_file(string $key): string
{
    return APP_ROOT . '/assets/img/puzzles/pals/' . preg_replace('/[^a-z0-9_-]/i', '', $key) . '.png';
}

/** Is this file the red-bordered placeholder (tools/pal_briefs.py --placeholders copies one reference image, pals/_placeholder.png, under every name)? */
function ppal_is_placeholder(string $file): bool
{
    static $ref = null;
    if ($ref === null) $ref = is_file(APP_ROOT . '/assets/img/puzzles/pals/_placeholder.png') ? md5_file(APP_ROOT . '/assets/img/puzzles/pals/_placeholder.png') : '';
    return $ref !== '' && md5_file($file) === $ref;
}

/** The pal's sticker URL, or '' when its art is missing (callers then draw nothing or an emoji, never a broken image). */
function ppal_art_url(string $key): string
{
    $f = ppal_art_file($key);
    return is_file($f) ? url('assets/img/puzzles/pals/' . basename($f)) : '';
}

/** Art-ready gate: every pal of the roster has a real (non-placeholder) PNG. A picture that is not art-ready releases nothing (admins see and release all). */
function ppal_art_ready(array $pic): bool
{
    $r = ppal_roster($pic);
    if (!$r) return false;
    foreach ($r as $p) {
        $f = ppal_art_file($p['key']);
        if (!is_file($f) || ppal_is_placeholder($f)) return false;
    }
    return true;
}

