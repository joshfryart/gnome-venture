const PPAL_RARITIES = ['common' => 60, 'uncommon' => 30, 'rare' => 10];   // rarity => find weight
const PPAL_CALLINGS = ['rootwarden', 'bloomcaller', 'thornblade', 'seedkeeper', 'wayfinder', 'brewroot'];
const PPAL_PERKS = ['gather', 'road', 'finder', 'tinker', 'bloom', 'shine'];
/** The perk a pal brings when its row says "-": by calling. */
const PPAL_CALLING_PERK = ['rootwarden' => 'road', 'bloomcaller' => 'bloom', 'thornblade' => 'road', 'seedkeeper' => 'tinker', 'wayfinder' => 'finder', 'brewroot' => 'gather'];
const PPAL_KNOBS = ['round', 'keyhole', 'peg', 'tri', 'double', 'hook'];
const PPAL_SHAPES = ['corner-TT', 'corner-TB', 'corner-BB', 'edge-TTB', 'edge-TBB', 'edge-TBT', 'edge-BTB', 'inner-TTTT', 'inner-BBBB', 'inner-TBTB', 'inner-TTBB', 'inner-TTTB', 'inner-TBBB'];
const PPAL_COLS = 14;   // pic_slug|key|name|rarity|calling|grit|nimble|hardiness|luck|piece|shape|knob|perk|blurb
const PPAL_STATS_TOTAL = ['common' => [3, 4], 'uncommon' => [5, 5], 'rare' => [6, 6]];
const PPAL_PLACE_KINDS = ['haven', 'wonder', 'delve', 'lair'];
/** Per place kind: callings it favours, knob styles (haven round, wonder keyhole, delve peg, lair hook), and the rare whimsy pieces. */
const PPAL_KIND_STYLE = [
    'haven' => [['bloomcaller', 'rootwarden', 'brewroot'], ['round', 'peg'], ['whimsy-house', 'whimsy-leaf']],
    'wonder' => [['seedkeeper', 'wayfinder', 'bloomcaller'], ['keyhole', 'double'], ['whimsy-star', 'whimsy-moon']],
    'delve' => [['rootwarden', 'wayfinder', 'brewroot'], ['peg', 'tri'], ['whimsy-moon', 'whimsy-fox']],
    'lair' => [['thornblade', 'seedkeeper', 'rootwarden'], ['hook', 'tri'], ['whimsy-fox', 'whimsy-boat']],
];

/** Is Puzzle Pals open to this viewer? (Admins always; players need Jigsaw open and the ppal_open setting.) */
function ppal_open(): bool
{
    return is_admin() || (jigsaw_open() && setting('ppal_open') === '1');
}

/** Pals per roster the generator makes and authored rosters may not exceed (setting ppal_roster_size, 1 to 6, default 6). */
function ppal_roster_size(): int
{
    $v = setting('ppal_roster_size');
    return $v === '' ? 6 : max(1, min(6, (int)$v));
}

