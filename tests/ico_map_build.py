#!/usr/bin/env python3
"""Build game/includes/data/ico_map.php from tests/ico_map_source.json.

Usage: python3 tests/ico_map_build.py [--only-existing] [--audit PATH] [--check]
  --only-existing  emit only rows whose game/assets/img/ico/{slug}.svg exists (default: all; the PHP filter ignores missing svgs)
  --audit PATH     emoji_audit.json (contexts/kinds) used to pick decorative vs named. Default: tests/ico_src/emoji_audit.json,
                   else the path in $EMOJI_AUDIT. Without it every emoji is decorative except the status set.

Entries with slug "skip" are not mapped.
Source (tests/ico_map_source.json, sorted, human-editable): emoji => {slug, group, reuse, note} plus optional
  "decorative": true|false and "name": "Accessible name" to override the rule below. Keys are exactly as the audit lists them
  (VS16 kept where the audit has it; ZWJ sequences whole).

Decorative rule (alt="" when decorative, else alt=name):
  1. STATUS marks (check/cross/lock/energy/warning...: the icon carries the meaning on its own) -> named.
  2. If the audit shows the emoji as the ONLY content of an element or quoted cell
     (>🌱< between tags, outside aria-hidden scenery) -> named.
  3. Otherwise it sits next to text (labels, buttons, headings) -> decorative.
Forms emitted: the key as given, its bare form (VS16 removed) and, for single-codepoint emoji, the VS16 form.
ZWJ sequences, flags and keycaps get no invented variants.
"""
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SRC = os.path.join(ROOT, 'tests', 'ico_map_source.json')
OUT = os.path.join(ROOT, 'game', 'includes', 'data', 'ico_map.php')
ICO = os.path.join(ROOT, 'game', 'assets', 'img', 'ico')
VS = '️'
STATUS = {'✔', '✅', '❌', '✖', '✓', '❎', '🔒', '🔓', '⚡', '⚠', '🚫', '⛔', '❗', '❓', '☑', '✗', '✘', '❕', '❔', '🔔', '🔕', '⭐', '❤', '💔'}


def bare(e):
    return e.replace(VS, '')


def standalone(e, contexts):
    b = re.escape(bare(e)) + VS + '?'
    pat = re.compile(r'>\s*' + b + r'\s*<')
    for c in contexts:
        if 'aria-hidden' in c:
            continue
        for m in pat.finditer(c):
            if '=>' in c[max(0, m.start() - 4):m.start() + 1] or c[max(0, m.start() - 6):m.start() + 1].rstrip().endswith('=>'):
                continue
            return True
    return False


def title(slug):
    return slug[4:].replace('-', ' ').capitalize()


def main():
    only = '--only-existing' in sys.argv
    audit = None
    if '--audit' in sys.argv:
        audit = sys.argv[sys.argv.index('--audit') + 1]
    else:
        for p in (os.path.join(ROOT, 'tests', 'ico_src', 'emoji_audit.json'), os.environ.get('EMOJI_AUDIT', '')):
            if p and os.path.exists(p):
                audit = p
                break
    ctx = {}
    if audit:
        for r in json.load(open(audit, encoding='utf-8')):
            ctx.setdefault(bare(r['emoji']), []).extend(r.get('contexts', []))
    src = json.load(open(SRC, encoding='utf-8'))
    have = {f[:-4] for f in os.listdir(ICO) if f.endswith('.svg')} if os.path.isdir(ICO) else set()
    rows, seen = [], {}
    nd = nn = 0
    for e in sorted(src):
        v = src[e]
        if v.get('skip') or v.get('slug') in (None, '', 'skip'):
            continue
        slug = v['slug']
        assert slug.startswith('ico-') and re.fullmatch(r'[a-z0-9-]+', slug), (e, slug)
        if only and slug not in have:
            continue
        dec = v['decorative'] if 'decorative' in v else not (bare(e) in STATUS or standalone(e, ctx.get(bare(e), [])))
        name = v.get('name') or title(slug)
        row = (slug, dec, name)
        forms = [e, bare(e)]
        if len(bare(e)) == 1:
            forms += [bare(e) + VS]
        for f in dict.fromkeys(forms):
            if f in seen and seen[f] != row:
                sys.exit('conflict for %r: %r vs %r' % (f, seen[f], row))
            seen[f] = row
        if dec: nd += 1
        else: nn += 1
    def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'")
    def key(f): return "'" + ''.join(c if ord(c) < 0x1F000 and c not in ('‍', VS) and ord(c) > 0x7e or 0x20 <= ord(c) < 0x7f and c not in "'\\" else ('\\u{%X}' % ord(c)) for c in f) + "'"
    lines = ['<?php', '// GENERATED by tests/ico_map_build.py — edit tests/ico_map_source.json', '// emoji => [slug, decorative(bool), accessible name (used when decorative is false)]. Bare and VS16 (U+FE0F) forms both listed; ZWJ sequences whole.', 'return [']
    for f in sorted(seen, key=lambda f: (seen[f][0], f)):
        slug, dec, name = seen[f]
        k = "\"" + ''.join(('\\u{%X}' % ord(c)) if c in ('‍', VS) else c for c in f) + "\""
        lines.append('    %s => [%s, true],' % (k, "'" + slug + "'") if dec else '    %s => [%s, false, \'%s\'],' % (k, "'" + slug + "'", esc(name)))
    lines.append('];')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    slugs = {v[0] for v in seen.values()}
    ok = sorted(slugs & have); miss = sorted(slugs - have)
    print('emoji %d (rows %d) decorative %d named %d | svg present %d, missing %d' % (len(src), len(seen), nd, nn, len(ok), len(miss)))
    print('MISSING SVG (%d): %s' % (len(miss), ' '.join(miss)))
    print('HAVE SVG (%d): %s' % (len(ok), ' '.join(ok)))


if __name__ == '__main__':
    main()
