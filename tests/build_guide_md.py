#!/usr/bin/env python3
"""Writes claude/art-style-guide.md from tests/guide_src/text.py (the same text as the PDF). usage: python3 tests/build_guide_md.py
Data tables ({{TOKEN}} lines) are not repeated here: the palette is filled from palette.json, the rest point at the PDF."""
import os, re, json, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, 'guide_src'))
import text as T

def palette_md():
    p = json.load(open(os.path.join(ROOT, 'game/assets/img/ph/palette.json'), encoding='utf-8'))
    rows = ['| family | steps (dark to light) |', '| --- | --- |']
    for fam, steps in p.items():
        if fam.startswith('_') or not isinstance(steps, dict): continue
        rows.append('| %s | %s |' % (fam, ' '.join('%s `%s`' % (k, v) for k, v in sorted(steps.items(), key=lambda kv: -int(kv[0])))))
    return '\n'.join(rows)

def fill(m):
    name = m.group(1)
    if name == 'PALETTE': return palette_md()
    return '_(table: see `game/assets/guides/Gnome-Venture-Style-Guide.pdf`, section "%s")_' % name.title()

def main():
    out = ['# Gnome Venture: art and style guide', '',
           'Generated by `python3 tests/build_guide_md.py` from `tests/guide_src/text.py` (the same text as the PDF `game/assets/guides/Gnome-Venture-Style-Guide.pdf`). '
           'Edit the text there, not here. The art rules were written from `tests/hearth.py`, `tests/hearth_all.py` and `claude/handoff.md`; they are not copied from an older hand-written guide.', '']
    part = None
    for sid, p, title, body in T.SECTIONS:
        if p != part and T.PARTS.get(p):
            out += ['# ' + T.PARTS[p], '']
        part = p
        body = re.sub(r'^\*Note: the art guide text was reconstructed.*\*\n?', '', body.strip('\n'), flags=re.M)
        body = re.sub(r'^\{\{([A-Z]+)(?::[^}]*)?\}\}$', fill, body, flags=re.M)
        body = re.sub(r'^(#{2,3}) ', lambda m: m.group(1) + '# ', body, flags=re.M)   # sections are h2 here
        out += ['## ' + title, '', body, '']
    open(os.path.join(ROOT, 'claude/art-style-guide.md'), 'w', encoding='utf-8').write('\n'.join(out).rstrip('\n') + '\n')
    print('wrote claude/art-style-guide.md')

if __name__ == '__main__': main()
