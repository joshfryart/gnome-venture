#!/usr/bin/env python3
import json, glob, os, base64, collections, html
from build import TYPE_TXT, TAG_TXT, MOD_TXT, ORDER, NAME, LEVEL, CATS
IT=json.load(open('pieces.json'))
ART='/home/user/gnome-venture/aseprite-source/v3/art-wear-concepts'
FAM={'b':'body','m':'mind','c':'craft'}
def icon_path(x):
    return glob.glob(f"{ART}/{x['region']}/{x['cat']}-{x['n']}-*.png")[0]
def slug(x): return x['region'].lower()+'-'+os.path.basename(icon_path(x))[len(x['cat'])+3:-4]
def effect(x):
    t=TYPE_TXT[x['type']].replace('#',str(x['v'])); parts=[t]
    if x['tag']!='-': parts.append(TAG_TXT[x['tag']])
    if x['mod']!='-': parts.append(MOD_TXT[x['mod']])
    dl={'quick':2,'hold':4}.get(x['tag'],3)
    if x['life']!=dl: parts.append(f"Lasts {x['life']} rounds on the board")
    return '. '.join(parts)+'.'
for x in IT: x['slug']=slug(x); x['effect']=effect(x)
# ---- markdown
L=['# Wearable puzzle pieces (280)','','Generated by `claude/wear-pieces/` (`design.py` -> `build.py` -> `render.py` -> `outputs.py`). Nothing here is installed in `game/`.','',
 '**Value** is the piece base; the game adds your stat, level/3 and rank (Common +0, Lined +2, Fine +4). **Petals** = Tailor price of the Common rank (Lined x2, Fine x3, as `wear_items()`). **Tailor** = lowest Tailor level that can craft it; **Energy** = crafting cost.','']
for r in ORDER:
    rows=[x for x in IT if x['region']==r]
    L+=[f"## {NAME[r]} ({r}, region level {LEVEL[r]})",'']
    for cat in CATS:
        L+=[f"### {cat.title()}",'','| # | Item | Rarity | Piece | Type | Value | Effect | Knob | Petals | Tailor | Energy |','|---|---|---|---|---|---|---|---|---|---|---|']
        for x in [y for y in rows if y['cat']==cat]:
            L.append(f"| {x['n']} | {x['item']} | {x['rarity']} | **{x['piece']}** | {x['type']} | {x['v']} | {x['effect']} | {FAM[x['knob']]} | {x['petals']} | {x['tailor']} | {x['energy']} |")
        L.append('')
open('pieces.md','w').write('\n'.join(L))
# ---- data file in pf_pieces.txt format
D=['# Wearable pieces (280): key|name|source|ref|type|v|knob|tag|life|rarity|blurb|mod   (not installed; proposal 2.7.xx; same columns as pf_pieces.txt)']
for x in IT:
    dl={'quick':2,'hold':4}.get(x['tag'],3)
    D.append('|'.join([f"w:{x['slug']}",x['piece'],'wear',x['slug'],x['type'],str(x['v']),FAM[x['knob']],x['tag'],'-' if x['life']==dl else str(x['life']),'src',f"{x['item']}: {x['effect']}",x['mod'] if x['mod']!='-' else '-']))
open('wear_pieces.txt','w').write('\n'.join(D)+'\n')
json.dump(IT,open('pieces.json','w'),indent=1)
print('md/txt written')
