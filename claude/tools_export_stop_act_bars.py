#!/usr/bin/env python3
"""Write game/includes/data/stop_act_bars.txt (read by game/includes/stop_marks.php) from claude/proposal-stop-act-bars.txt.

    python3 claude/tools_export_stop_act_bars.py

Input rows: `slug | stop type | first bar | second bar or - | base points` (generated by tools_gen_stop_act_bars.py, rules
proposal-stop-perks.md section 2). The 60 suggested hand overrides at the end of the input (`# slug|-|meter:<bar>+10`) are
applied: the override names the first bar for every type and, as rule step 0 says, no second bar (only one bar is listed).
Base points are left out: the game works B out from the act's energy (master doc 7.3), so an Admin energy edit is honoured.
Output rows: `slug | type | bar | second` (bars lower case, type `*` = every type). Deterministic.
"""
import os
import re

CL = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(CL, 'proposal-stop-act-bars.txt')
OUT = os.path.join(os.path.dirname(CL), 'game', 'includes', 'data', 'stop_act_bars.txt')
BARS = ('repairs', 'larder', 'cheer')


def main():
    rows, overrides = [], {}
    with open(SRC, encoding='utf-8') as f:
        for ln in f:
            ln = ln.rstrip('\n')
            m = re.match(r'^#\s*([a-z0-9_]+)\|-\|meter:([a-z]+)\+\d+', ln)
            if m and m.group(2) in BARS:
                overrides[m.group(1)] = m.group(2)
                continue
            if not ln.strip() or ln.startswith('#'):
                continue
            c = [x.strip() for x in ln.split('|')]
            if len(c) != 5:
                raise SystemExit(f'bad row: {ln}')
            rows.append([c[0], c[1], c[2].lower(), c[3].lower() if c[3] != '-' else '-'])
    seen = set()
    for r in rows:
        if r[0] in overrides:
            r[2], r[3] = overrides[r[0]], '-'
        if r[2] not in BARS or (r[3] != '-' and r[3] not in BARS) or r[2] == r[3]:
            raise SystemExit(f'bad bars: {r}')
        seen.add(r[0])
    missing = sorted(set(overrides) - seen)
    if missing:
        raise SystemExit(f'override for an act not in the table: {missing}')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('# Generated by claude/tools_export_stop_act_bars.py from claude/proposal-stop-act-bars.txt: do not edit by hand.\n'
                '# Which bar each stop act feeds (lasting marks, stop_marks.php; master doc 7.2). Applied: the 60 suggested overrides.\n'
                '# slug | stop type (* = every type) | first bar | second bar (half points) or -\n')
        for r in rows:
            f.write(' | '.join(r) + '\n')
    print(f'{len(rows)} rows, {len(seen)} acts, {len(overrides)} overrides applied -> {os.path.relpath(OUT, os.path.dirname(CL))}')


if __name__ == '__main__':
    main()
